# ---------------------- PyTorch 2.6+ patch ----------------------
# Global patch for PyTorch >= 2.6 to safely load checkpoints that
# contain argparse.Namespace objects during deserialization.
_original_torch_load = torch.load

def safe_torch_load(*args, **kwargs):
    """
    Wrapper around torch.load that disables weights_only mode and
    allows safe loading of argparse.Namespace objects.
    """
    kwargs["weights_only"] = False  # force full checkpoint loading
    with torch.serialization.safe_globals([argparse.Namespace]):
        return _original_torch_load(*args, **kwargs)

torch.load = safe_torch_load
