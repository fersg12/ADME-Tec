# Path to the local CSV generated by chembl_data.py
DATA_PATH = os.path.join(os.path.dirname(__file__), "chembl_mechanisms_clinical2.csv")


def get_mechanism_metadata(chembl_target: str) -> pd.DataFrame:
    """
    Retrieve compounds associated with a ChEMBL target from a local CSV file.

    Parameters
    ----------
    chembl_target : str
        Target ChEMBL identifier (e.g., CHEMBL204).

    Returns
    -------
    pd.DataFrame
        DataFrame containing compounds linked to the target,
        filtered to rows with valid canonical SMILES and renamed
        to include a standardized 'smiles' column.

    Raises
    ------
    FileNotFoundError
        If the local CSV file is missing.
    """
    if not os.path.exists(DATA_PATH):
        raise FileNotFoundError(
            f"{DATA_PATH} not found. Run chembl_data.py first."
        )

    df = pd.read_csv(DATA_PATH)

    # Filter by target and ensure SMILES availability
    df = df[df["target_chembl_id"] == chembl_target].dropna(subset=["canonical_smiles"])

    # Standardize column name
    df = df.rename(columns={"canonical_smiles": "smiles"})

    return df.reset_index(drop=True)


def get_chembl_adme_properties(chembl_target: str) -> pd.DataFrame:
    """
    Retrieve compounds for a ChEMBL target and compute ADME properties
    using curated SMILES strings.

    Workflow
    --------
    1. Load mechanism metadata for the target.
    2. Standardize and validate SMILES with `process_molecule_row`.
    3. Predict ADME properties using ADMETModel.
    4. Attach original ChEMBL identifiers for traceability.

    Parameters
    ----------
    chembl_target : str
        Target ChEMBL identifier.

    Returns
    -------
    pd.DataFrame
        DataFrame containing ADME predictions for curated compounds.
        Returns an empty DataFrame if no valid compounds are available.
    """
    df_mechanism = get_mechanism_metadata(chembl_target)

    if df_mechanism.empty or "smiles" not in df_mechanism.columns:
        print(f"No compounds found for {chembl_target}")
        return pd.DataFrame()

    # --- Curate SMILES ---
    processed_df = df_mechanism[["smiles"]].apply(
        process_molecule_row, axis=1, result_type="expand"
    )

    # Keep successfully processed molecules
    valid_df = processed_df[processed_df["error"].isna()].reset_index(drop=True)
    curated_smiles = valid_df["curated_smiles"].dropna().tolist()

    if not curated_smiles:
        print(f" No valid SMILES after standardization for {chembl_target}")
        return pd.DataFrame()

    try:
        # --- ADME prediction ---
        model = ADMETModel()
        adme_predictions = model.predict(smiles=curated_smiles)
        adme_df = pd.DataFrame(adme_predictions)

        # Link predictions to original ChEMBL metadata
        adme_df["chembl_id"] = df_mechanism["molecule_chembl_id"].values[: len(adme_df)]
        adme_df["target_id"] = chembl_target  # traceability

        return adme_df

    except Exception as e:
        print(f"Error predicting ADME properties for {chembl_target}: {e}")
        return pd.DataFrame()


def retrieve_chembl_data(target_id: str, selected_actions: list):
    """
    Retrieve filtered ChEMBL mechanism data and corresponding ADME predictions.

    Parameters
    ----------
    target_id : str
        Target ChEMBL identifier.
    selected_actions : list
        List of action types to filter (e.g., ["AGONIST", "INHIBITOR"]).

    Returns
    -------
    tuple (pd.DataFrame, pd.DataFrame)
        - Filtered ChEMBL metadata DataFrame.
        - ADME prediction DataFrame for curated SMILES.
        Returns empty DataFrames if no data is available.
    """
    chembl_df = get_mechanism_metadata(target_id)

    if chembl_df.empty:
        return pd.DataFrame(), pd.DataFrame()

    # Filter by mechanism of action
    filtered_df = chembl_df[chembl_df["action_type"].isin(selected_actions)].reset_index(
        drop=True
    )

    chembl_smiles = filtered_df["smiles"].dropna().tolist()

    if not chembl_smiles:
        return filtered_df, pd.DataFrame()

    # --- Curate SMILES ---
    processed_df = pd.DataFrame({"smiles": chembl_smiles}).apply(
        process_molecule_row, axis=1, result_type="expand"
    )

    valid_df = processed_df[processed_df["error"].isna()]
    curated_smiles = valid_df["curated_smiles"].tolist()

    # --- ADME prediction ---
    adme_predictions = ADMETModel().predict(smiles=curated_smiles)
    adme_chembl_df = pd.DataFrame(adme_predictions)

    # Attach identifiers
    adme_chembl_df["chembl_id"] = filtered_df["molecule_chembl_id"].values[
        : len(adme_chembl_df)
    ]

    return filtered_df, adme_chembl_df


